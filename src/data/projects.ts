export interface ProjectImage {
  url: string;
  alt: string;
}

export interface Project {
  /** URL segment: /kitchens/<slug> */
  slug: string;
  /** The kitchen's own name — the page's H1. */
  title: string;
  /** One line under the title, on the card and the page hero. */
  subtitle: string;
  /** Short copy for the gallery card. */
  excerpt: string;
  /** Full copy on the project page. Each entry is a paragraph. */
  body: string[];
  /** Spec rows shown on the project page. */
  specs: { label: string; value: string }[];
  /** The frame used for the card and the page hero. */
  coverImage: string;
  coverAlt: string;
  /** Bento layout weight — 'wide' and 'tall' tiles span two columns/rows on desktop. */
  span?: 'wide' | 'tall';
  images: ProjectImage[];
}

const build = (
  slug: string,
  title: string,
  subtitle: string,
  excerpt: string,
  body: string[],
  specs: Project['specs'],
  /* [filename, alt] — alt is written per frame rather than numbered, so a screen reader
     hears what is actually pictured. */
  files: [string, string][],
  cover: string,
  span?: Project['span'],
): Project => {
  const images = files.map(([file, altText]) => ({
    url: `/images/${file}`,
    alt: `${altText} — ${title}, מטבחי דניאל`,
  }));
  const coverImage = `/images/${cover}`;

  return {
    slug,
    title,
    subtitle,
    excerpt,
    body,
    specs,
    coverImage,
    coverAlt: images.find((image) => image.url === coverImage)?.alt ?? images[0].alt,
    span,
    images,
  };
};


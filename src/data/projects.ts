export interface ProjectImage {
  url: string;
  alt: string;
}

export interface Project {
  id: string;
  title: string;
  /** Shown on the card and in the lightbox header. */
  subtitle: string;
  /** Longer copy, shown inside the lightbox only. Describes what the frames show. */
  description: string;
  coverImage: string;
  /** Alt of the cover frame specifically — the cover is not always `images[0]`. */
  coverAlt: string;
  /** Bento layout weight — 'wide' and 'tall' tiles span two columns/rows on desktop. */
  span?: 'wide' | 'tall';
  images: ProjectImage[];
}

const build = (
  id: string,
  title: string,
  subtitle: string,
  description: string,
  /* [filename, alt] — alt text is written per frame rather than numbered, so a screen
     reader hears what is actually pictured. */
  files: [string, string][],
  cover: string,
  span?: Project['span'],
): Project => {
  const images = files.map(([file, altText]) => ({
    url: `/images/${file}`,
    alt: `${altText} — ${title}, מטבחי דניאל`,
  }));
  const coverImage = `/images/${cover}`;

  return {
    id,
    title,
    subtitle,
    description,
    coverImage,
    coverAlt: images.find((image) => image.url === coverImage)?.alt ?? images[0].alt,
    span,
    images,
  };
};

